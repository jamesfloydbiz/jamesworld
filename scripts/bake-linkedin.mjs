/**
 * Bake the LinkedIn posts list into site/writing/index.html.
 *
 * Source: public/data/linkedin-posts.json (207 posts, ranked best-first,
 * hand-curated subset of 30).
 *
 * Reads the JSON, generates a static <li> per post (collapsed card: hook,
 * date, engagement stats, image count), and a hidden <div class="li-post-body">
 * with the full bodyHtml + lazy <img loading="lazy"> for each media file.
 *
 * Injects between <!-- BEGIN_LI_POSTS --> / <!-- END_LI_POSTS --> markers
 * so /writing/ stays static-HTML for crawlers.
 *
 * Run at build time alongside fetch-substack.mjs.
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const JSON_PATH = resolve(__dirname, '..', 'public', 'data', 'linkedin-posts.json');
const HTML_PATH = resolve(__dirname, '..', 'site', 'writing', 'index.html');

const escAttr = (s) =>
  String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const escText = (s) =>
  String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

function formatDate(iso) {
  const d = new Date(iso);
  if (isNaN(d)) return iso;
  // Use UTC so an ISO date like "2026-03-06" doesn't get shifted back a day
  // when the runner happens to be in a negative-offset timezone.
  return d.toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric', timeZone: 'UTC' });
}

function formatEngagement(eng) {
  if (!eng) return '';
  const parts = [];
  if (eng.impressions) parts.push(`${eng.impressions.toLocaleString()} impressions`);
  if (eng.reactions) parts.push(`${eng.reactions} reactions`);
  if (eng.comments) parts.push(`${eng.comments} comments`);
  return parts.join(' · ');
}

function mediaPath(rel) {
  // Package paths look like "media/2026-03-06_foo.jpg" — rewrite to /linkedin/...
  return '/linkedin/' + rel.replace(/^\/+/, '');
}

function isImage(rel) {
  return /\.(jpe?g|png|gif|webp)$/i.test(rel);
}
function isPdf(rel) {
  return /\.pdf$/i.test(rel);
}

function renderPost(p) {
  const hook = (p.hook || (p.text || '').split('\n')[0] || '').trim();
  const displayDate = formatDate(p.date);
  const eng = formatEngagement(p.engagement);
  const imageCount = (p.images || []).filter(isImage).length;
  const carouselCount = (p.documents || []).filter(isPdf).length;

  const meta = [displayDate];
  if (eng) meta.push(eng);

  // Build the hidden body: bodyHtml + lazy <img> per image, then PDF download
  // links for carousels.
  const bodyParts = [];
  bodyParts.push(p.bodyHtml || `<p>${escText(p.text || '')}</p>`);

  for (const img of (p.images || []).filter(isImage)) {
    const src = mediaPath(img);
    bodyParts.push(`<img src="${escAttr(src)}" loading="lazy" alt="" style="max-width:100%;height:auto;display:block;margin:1rem 0;border-radius:2px;">`);
  }
  for (const pdf of (p.documents || []).filter(isPdf)) {
    const src = mediaPath(pdf);
    bodyParts.push(`<p><a href="${escAttr(src)}" target="_blank" rel="noopener noreferrer" class="prose-link">Open carousel PDF →</a></p>`);
  }

  // Tags so the JS can filter/sort without re-parsing
  const dataAttrs = [
    `data-id="${escAttr(p.id || '')}"`,
    `data-link="${escAttr(p.url || '')}"`,
    `data-date="${escAttr(p.date || '')}"`,
    `data-display-date="${escAttr(displayDate)}"`,
    `data-quality="${escAttr(String(p.qualityScore || 0))}"`,
    `data-rank="${escAttr(String(p.rank || 9999))}"`,
    `data-curated="${p.curated ? 'true' : 'false'}"`,
  ].join(' ');

  const chips = [];
  if (imageCount) chips.push(`<span class="li-post-chip">${imageCount} photo${imageCount > 1 ? 's' : ''}</span>`);
  if (carouselCount) chips.push(`<span class="li-post-chip">${carouselCount} carousel</span>`);

  return `          <li class="li-post-item" ${dataAttrs}>
            <button class="li-post-btn" type="button">
              <p class="li-post-meta">${escText(meta.join(' · '))}${chips.length ? ` · ${chips.join(' ')}` : ''}</p>
              <h3 class="li-post-hook">${escText(hook)}</h3>
              <span class="li-post-cta">Read full post →</span>
            </button>
            <div class="li-post-body-html" hidden>${bodyParts.join('\n')}</div>
          </li>`;
}

function bake() {
  const data = JSON.parse(readFileSync(JSON_PATH, 'utf8'));
  const posts = data.posts || [];

  // Sort posts best-first (by rank ascending — rank 1 is best).
  posts.sort((a, b) => (a.rank || 9999) - (b.rank || 9999));

  const rendered = posts.map(renderPost).join('\n');

  if (!existsSync(HTML_PATH)) {
    console.warn('  ! writing page not found, skipping LinkedIn bake');
    return;
  }
  const src = readFileSync(HTML_PATH, 'utf8');
  const begin = '<!-- BEGIN_LI_POSTS — regenerated by scripts/bake-linkedin.mjs; do not edit by hand. -->';
  const end = '<!-- END_LI_POSTS -->';
  const b = src.indexOf(begin);
  const e = src.indexOf(end);
  if (b < 0 || e < 0 || e <= b) {
    console.warn('  ! BEGIN_LI_POSTS/END_LI_POSTS markers not found in writing/index.html — skipping LinkedIn bake');
    return;
  }
  const before = src.slice(0, b + begin.length);
  const after = src.slice(e);
  const next = `${before}\n${rendered}\n        ${after}`;

  // Sync counts on the data attributes
  const curated = posts.filter((p) => p.curated).length;
  const updated = next
    .replace(/<ul class="li-post-list" id="li-post-list"[^>]*>/, (m) =>
      m
        .replace(/data-post-count="\d+"/, `data-post-count="${posts.length}"`)
        .replace(/data-curated-count="\d+"/, `data-curated-count="${curated}"`)
    );

  writeFileSync(HTML_PATH, updated);
  console.log(`✓ baked ${posts.length} LinkedIn posts (${curated} curated) → site/writing/index.html`);
}

bake();
